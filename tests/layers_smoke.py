"""Regression check for primary + secondary + multiple decorative sources."""
import os,sys
from playwright.sync_api import sync_playwright,expect
base=sys.argv[1] if len(sys.argv)>1 else 'http://127.0.0.1:4176'
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1100})
    page.goto(base,wait_until='networkidle')
    page.get_by_role('button',name='Switch to manual',exact=True).click()
    page.locator('.steps .step').nth(2).click()
    expect(page.get_by_label('Primary lighting source',exact=True)).to_have_value('Recessed spotlights')
    expect(page.locator('.layer-row')).to_have_count(0)
    page.get_by_role('button',name='Add secondary lighting',exact=True).click()
    expect(page.get_by_label('Secondary fixture',exact=True)).to_have_value('Magnetic track lighting')
    expect(page.locator('.primary-layer-card')).to_contain_text('7 planned fixtures')
    page.get_by_role('button',name='Add decorative lighting',exact=True).click()
    page.get_by_role('button',name='Add decorative lighting',exact=True).click()
    page.get_by_label('Decorative fixture',exact=True).last.select_option('Wall-mounted lights')
    page.get_by_label('Decorative lumens per unit',exact=True).last.fill('400')
    page.get_by_label('Decorative watts per unit',exact=True).last.fill('5')
    expect(page.locator('.layer-row')).to_have_count(3)
    expect(page.locator('.primary-layer-card')).to_contain_text('7 planned fixtures')
    expect(page.locator('.result-facts')).to_contain_text('133 W')
    secondary=page.locator('.source-secondary')
    secondary.locator('summary').filter(has_text='Secondary calculation settings').click()
    secondary.get_by_label('Credit this group to the average task-plane illuminance',exact=True).uncheck()
    expect(page.locator('.primary-layer-card')).to_contain_text('11 planned fixtures')
    secondary.get_by_label('Credit this group to the average task-plane illuminance',exact=True).check()
    expect(page.locator('.primary-layer-card')).to_contain_text('7 planned fixtures')
    assert page.get_by_label('Primary lumens per unit',exact=True).evaluate("e=>parseFloat(getComputedStyle(e).fontSize)")>=16
    assert page.locator('.primary-layer-card .field').first.evaluate("e=>parseFloat(getComputedStyle(e).fontSize)")>=14
    page.locator('.primary-layer-card').scroll_into_view_if_needed()
    page.screenshot(path='/tmp/luma-checks/v21-primary-secondary-desktop.png')
    page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(250)
    assert not page.evaluate('document.documentElement.scrollWidth>innerWidth')
    assert page.get_by_label('Primary lumens per unit',exact=True).evaluate("e=>parseFloat(getComputedStyle(e).fontSize)")>=16
    page.locator('.primary-layer-card').scroll_into_view_if_needed()
    page.screenshot(path='/tmp/luma-checks/v21-primary-secondary-mobile.png')
    page.locator('.steps .step').nth(4).click()
    expect(page.locator('.source-breakdown tbody tr')).to_have_count(4)
    expect(page.locator('.source-breakdown')).to_contain_text('Magnetic track lighting')
    expect(page.locator('.source-breakdown')).to_contain_text('Cove lighting')
    expect(page.locator('.source-breakdown')).to_contain_text('Wall-mounted lights')
    expect(page.locator('.source-breakdown tfoot')).to_contain_text('133 W')
    page.get_by_role('button',name='Save project',exact=True).last.click()
    page.get_by_role('button',name='Open navigation',exact=True).click()
    page.get_by_role('button',name='My projects',exact=False).click()
    page.get_by_role('button',name='Open plan',exact=False).click()
    expect(page.locator('.source-breakdown tbody tr')).to_have_count(4)
    print('PASS: primary spots + secondary magnetic track + decorative cove and wall sources; same-plane credit; source totals; saved/reopened layers; >=16px inputs and >=14px labels; mobile layout')
    browser.close()
