"""Browser smoke tests: python3 tests/browser_smoke.py [base URL].
Requires Python Playwright and an installed Chromium. Uses isolated browser storage.
"""
import sys,os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base=sys.argv[1] if len(sys.argv)>1 else 'http://127.0.0.1:4173'
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    ctx=browser.new_context(viewport={'width':1440,'height':1100},accept_downloads=True,permissions=['clipboard-read','clipboard-write'])
    page=ctx.new_page();page.set_default_timeout(10000);errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base,wait_until='networkidle')
    expect(page.locator('.big-number')).to_contain_text('200')
    expect(page.locator('.result-pair')).to_contain_text('8,333')
    page.get_by_label('Room name',exact=True).fill('')
    expect(page.get_by_role('alert')).to_contain_text('room name')
    page.get_by_label('Room name',exact=True).fill('Kitchen plan')
    page.get_by_label('Length',exact=True).fill('0')
    expect(page.get_by_role('alert')).to_contain_text('positive')
    page.get_by_label('Length',exact=True).fill('5')
    page.get_by_label('Room type',exact=True).select_option('Kitchen')
    page.get_by_label('Units',exact=True).select_option('Imperial · feet')
    assert abs(float(page.get_by_label('Length',exact=True).input_value())-16.404)<.002
    expect(page.locator('.area-strip')).to_contain_text('215.3')
    page.get_by_label('Units',exact=True).select_option('Metric · meters')
    page.get_by_role('button',name='Continue to lighting goal',exact=True).click()
    page.locator('.goal-card').filter(has_text='Functional').click()
    page.get_by_label('Natural light',exact=True).select_option('High natural light')
    page.get_by_label('Time-of-day scene',exact=True).select_option('Night / ambience')
    page.get_by_role('button',name='Continue to fixture preference',exact=True).click()
    expect(page.locator('.layer-row')).to_have_count(4)
    expect(page.get_by_label('Include secondary and decorative lighting',exact=False)).to_be_checked()
    expect(page.locator('.big-number')).to_contain_text('500')
    primary=page.locator('.result-pair>div').nth(1).locator('strong').inner_text()
    page.get_by_label('Task quantity',exact=True).fill('3')
    assert page.locator('.result-pair>div').nth(1).locator('strong').inner_text()==primary
    page.locator('summary').filter(has_text='Explore fixture illustrations').click()
    page.locator('.fixture-gallery button').filter(has_text='Magnetic track lighting').click()
    expect(page.locator('.chosen-fixture')).to_contain_text('Magnetic track lighting')
    page.get_by_role('button',name='Continue to technical details',exact=True).click()
    page.get_by_role('button',name='4000K',exact=True).click()
    page.locator('summary').filter(has_text='Advanced settings · photometry & layout').click()
    page.get_by_label('My output value is bare-source lumens',exact=False).check()
    page.get_by_label('Optical efficiency',exact=False).fill('0.8')
    page.get_by_role('button',name='See your lighting plan',exact=True).click()
    expect(page.locator('.detailed-results')).to_be_visible()
    expect(page.locator('.layer-summary article')).to_have_count(5)
    expect(page.locator('.technical-detail')).to_contain_text('Bare-source input')
    expect(page.locator('.detailed-results')).to_contain_text('Night / ambience')
    page.locator('summary').filter(has_text='Energy assumptions').click()
    page.get_by_label('Operating hours per day',exact=True).fill('')
    expect(page.get_by_role('alert')).to_contain_text('Hours per day')
    page.get_by_label('Operating hours per day',exact=True).fill('8')
    expect(page.locator('.energy-stats')).not_to_contain_text('—')
    page.get_by_role('button',name='Pin as option A',exact=True).click()
    page.locator('.steps .step').nth(3).click()
    page.get_by_label('Primary wattage',exact=True).fill('18')
    page.get_by_role('button',name='See your lighting plan',exact=True).click()
    expect(page.locator('.comparison')).to_be_visible()
    cells=page.locator('.comparison tr').filter(has_text='Connected load').locator('td').all_text_contents()
    assert cells[0]!=cells[1]
    page.get_by_role('button',name='Copy summary',exact=True).click()
    assert 'KITCHEN' in page.evaluate('navigator.clipboard.readText()').upper()
    page.evaluate('window.print=()=>{window.__printed=true}')
    page.get_by_role('button',name='Print / PDF',exact=True).click()
    page.wait_for_function('window.__printed===true')
    page.evaluate("window.dispatchEvent(new Event('afterprint'))")
    with page.expect_download() as d:page.get_by_role('button',name='Export report',exact=True).click()
    assert d.value.suggested_filename=='luma-Kitchen-plan.txt'
    page.get_by_role('button',name='Save project',exact=True).last.click()
    page.get_by_role('button',name='My projects',exact=False).click()
    expect(page.locator('.project-card')).to_have_count(1)
    page.get_by_role('button',name='Favorite Kitchen plan',exact=True).click()
    page.reload(wait_until='networkidle')
    page.get_by_role('button',name='My projects',exact=False).click()
    expect(page.get_by_role('button',name='Unfavorite Kitchen plan',exact=True)).to_be_visible()
    page.get_by_role('button',name='Duplicate room',exact=True).click()
    expect(page.get_by_label('Room name',exact=True)).to_have_value('Kitchen plan · copy')
    page.get_by_role('button',name='Save project',exact=True).click()
    page.get_by_role('button',name='My projects',exact=False).click()
    expect(page.locator('.project-card')).to_have_count(2)
    page.get_by_role('button',name='Show favorites',exact=True).click()
    expect(page.locator('.project-card')).to_have_count(1)
    page.get_by_role('button',name='Favorites only',exact=True).click()
    page.get_by_role('button',name='Delete Kitchen plan',exact=True).click()
    page.get_by_role('button',name='Delete Kitchen plan · copy',exact=True).click()
    expect(page.locator('.empty')).to_be_visible()
    page.get_by_role('button',name='New calculation',exact=True).click()
    for label,name in [('Download HTML','Luma-Lighting-Calculator.html'),('Source ZIP','Luma-Source-Code.zip')]:
        with page.expect_download() as d:page.get_by_role('button',name=label,exact=True).click()
        assert d.value.suggested_filename==name
        assert not d.value.failure()
    page.get_by_role('button',name='Lighting guide',exact=False).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.keyboard.press('Escape');expect(page.get_by_role('dialog')).to_have_count(0)
    page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(250)
    for index in range(5):
        page.locator('.steps .step').nth(index).click()
        assert not page.evaluate('document.documentElement.scrollWidth>innerWidth'),f'Mobile overflow on step {index+1}'
    page.screenshot(path='/tmp/luma-checks/v2-results-mobile.png',full_page=True)
    page.set_viewport_size({'width':1440,'height':1100});page.wait_for_timeout(250)
    page.screenshot(path='/tmp/luma-checks/v2-results-desktop.png',full_page=True)
    assert not errors,errors
    print('PASS: five-step smart flow, SI/imperial conversion, mixed layers, photometric overrides, energy error recovery, comparison, clipboard, print, export, persistence, favorites, duplication, deletion, downloads, modal keyboard controls and mobile layouts')
    offline=browser.new_context(viewport={'width':390,'height':844})
    tab=offline.new_page();tab.goto(base,wait_until='networkidle');tab.evaluate('navigator.serviceWorker.ready');offline.set_offline(True);tab.reload(wait_until='networkidle')
    tab.get_by_label('Length',exact=True).fill('6');expect(tab.locator('.result-pair')).to_contain_text('10,000')
    print('PASS: production PWA offline reload and calculation')
    browser.close()
